/*
 * product_info.h - 量产产品信息配置区
 *
 * ★★ 出厂 / 量产流程: 每次烧录前按台修改本文件的两项 -> 编译 -> 烧录, 不需要额外工具。
 *    固件上电时会把 SN 写入设备(MCU 内部 Flash 末页 0x0803F800 持久化),
 *    并同步显示到屏端"设置页"的 产品编号 / 固件版本 两行。
 *
 * 存放位置说明: SN 落盘在 MCU **内部** Flash 最后一页, 与 W25Q64 的参数区/历史区无关,
 *              因此"恢复出厂"不会清除它(出厂标识本就不应被恢复出厂重置)。
 */
#ifndef PRODUCT_INFO_H
#define PRODUCT_INFO_H

/* =================== 量产配置区（逐台 / 逐批修改） =================== */

/* 固件版本 —— 整批相同。屏端设置页"固件版本"行显示的就是它(可用 10 字符)。
 * 约定: 产品版本 + 构建号, 构建号与内部迭代号对齐 -> V1.0.0-b<N>
 * v65: 厂家页五按钮「自动恢复默认 + 待确认超时解锁 + 标定状态实时刷新」
 *      恢复出厂两段确认由屏端移交固件(屏端 cf 改单发 D5/5A/17)
 * v66: 修复「五按钮连点后只有最后一个能恢复」—— 恢复计时由单变量改为按操作索引的数组 */
#define PRODUCT_FW_VERSION   "V1.0-b98"

/* 产品编号 —— 量产时逐台修改。屏端设置页"产品编号"行显示的就是它。
 *   填字符串 : 以本值为准(是否覆写设备内旧值, 见下方写入策略)
 *   填 ""    : 不指定, 改用 MCU 唯一 ID 自动派生 "SN-C4F7N-XXXXXXXX"
 *              (逐台唯一且无需人工维护, 适合不想逐台编号的场合) */
#define PRODUCT_SN           "C4F7N-26001"

/* 屏端"产品编号"行可显示的字符数上限(ASCII 字符)。
 *   = 屏端 sn 控件 txt_maxl(30B) − 前缀 "产品编号: "(10B) = 20
 *   ⚠️ 超过此长度的 PRODUCT_SN 会被屏端静默截断(无任何报错), 故在 device_id.c 里做了编译期断言。
 *   ⚠️ 若在编辑器里改了 sn 控件的前缀或 txt_maxl, 必须同步改这里。 */
#define PRODUCT_SN_DISPLAY_MAX   20u

/* SN 写入策略(只影响"设备内已有记录"的情况):
 *   1 = 宏值与设备内记录不一致时覆写  (推荐: 量产/研发改号后重烧即生效)
 *   0 = 仅当设备内无有效记录时才写入  (保护已出厂编号: 仅重烧固件不会改掉它) */
#define PRODUCT_SN_FORCE_WRITE   1

/* ================================================================= */

#endif /* PRODUCT_INFO_H */
